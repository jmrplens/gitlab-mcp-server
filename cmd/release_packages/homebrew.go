// The tap the formula is published to, and the identity its commits carry,
// the one the script configured in the clone.
const (
	defaultTapRepo  = "git@github.com:jmrplens/homebrew-tap.git"
	tapFormula      = "Formula/gitlab-mcp-server.rb"
	tapAuthorName   = "José M. Requena Plens"
	tapAuthorEmail  = "jmrplens@gmail.com"
	releaseDownload = "https://github.com/jmrplens/gitlab-mcp-server/releases/download/v"
	licenseRaw      = "https://raw.githubusercontent.com/jmrplens/gitlab-mcp-server/v"
)

// formulaVersion finds the version a formula declares, as the script's sed
// did: the first line that is only `version "..."`.
var formulaVersion = regexp.MustCompile(`(?m)^[ \t]*version "(.*)"[ \t]*$`)

// formulaTemplate is the formula, each ${NAME} replaced by its value. The
// header opens it, where make check-file-headers puts it in a Ruby file, and
// ${DASH} is the em dash the generated note carries.
const formulaTemplate = `${HEADER}

# typed: false
# frozen_string_literal: true

# This file is generated by the release workflow of
# https://github.com/jmrplens/gitlab-mcp-server ${DASH} do not edit by hand.
class GitlabMcpServer < Formula
  desc "GitLab MCP server: REST v4 + GraphQL as tools for AI assistants"
  homepage "https://docs.jmrp.io/gitlab-mcp-server/"
  version "${VERSION}"
  license "MIT"

  livecheck do
    url "https://github.com/jmrplens/gitlab-mcp-server"
    strategy :github_latest
  end

  on_macos do
    on_arm do
      url "${BASE_URL}/gitlab-mcp-server-darwin-arm64"
      sha256 "${SHA_DARWIN_ARM}"
    end
    on_intel do
      url "${BASE_URL}/gitlab-mcp-server-darwin-amd64"
      sha256 "${SHA_DARWIN_INTEL}"
    end
  end

  on_linux do
    on_arm do
      url "${BASE_URL}/gitlab-mcp-server-linux-arm64"
      sha256 "${SHA_LINUX_ARM}"
    end
    on_intel do
      url "${BASE_URL}/gitlab-mcp-server-linux-amd64"
      sha256 "${SHA_LINUX_INTEL}"
    end
  end

  resource "license" do
    url "${LICENSE_URL}"
    sha256 "${SHA_LICENSE}"
  end

  resource "third-party-notices" do
    url "${BASE_URL}/THIRD_PARTY_NOTICES"
    sha256 "${SHA_NOTICES}"
  end

  def install
    bin.install Dir["gitlab-mcp-server-*"].first => "gitlab-mcp-server"
    resource("license").stage { prefix.install "LICENSE" }
    resource("third-party-notices").stage { prefix.install "THIRD_PARTY_NOTICES" }
  end

  def caveats
    <<~EOS
      Homebrew manages upgrades for this binary.

      Configure your MCP client with:
        command: #{HOMEBREW_PREFIX}/bin/gitlab-mcp-server
        env:     GITLAB_TOKEN=glpat-... (and GITLAB_URL for self-managed)

      Per-client JSON:
        https://docs.jmrp.io/gitlab-mcp-server/configuration/
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/gitlab-mcp-server --version")
  end
end
`

// tapUpdate is one run of the homebrew subcommand.
type tapUpdate struct {
	root, checksums, version, tapDir string
	dryRun                           bool
	env                              []string
	stdout, stderr                   io.Writer
}

// runHomebrew is the homebrew subcommand, scripts/update-homebrew-tap.sh
// moved into Go: it renders the tap's formula from the release version, the
// hashes checksums.txt names and the LICENSE beside it, checks it with
// ruby -c, commits it to a clone of the tap and pushes it, or with --dry-run
// shows the commit instead. env is the environment git and ruby run with,
// and TAP_REPO in it names the tap to clone.
func runHomebrew(root string, args []string, stdout, stderr io.Writer, env []string) int {
	u := &tapUpdate{root: root, env: env, stdout: stdout, stderr: stderr}
	var positional []string
	for _, arg := range args {
		if arg == "--dry-run" {
			u.dryRun = true
			continue
		}
		positional = append(positional, arg)
	}
	if len(positional) < 2 || len(positional) > 3 {
		fmt.Fprintf(stderr, "%s: homebrew takes <checksums-file> <version> [tap-clone-dir] [--dry-run]\n%s", toolName, usage)
		return 2
	}
	u.checksums, u.version, u.tapDir = positional[0], positional[1], optional(positional, 2, "homebrew-tap")
	return u.run()
}

// errorf writes one ERROR line and returns 1.
func (u *tapUpdate) errorf(format string, args ...any) int {
	fmt.Fprintf(u.stderr, "ERROR: "+format+"\n", args...)
	return 1
}

// lookup is the value of a variable in the run's environment.
func (u *tapUpdate) lookup(name string) string {
	value := ""
	for _, entry := range u.env {
		if key, v, ok := strings.Cut(entry, "="); ok && key == name {
			value = v
		}
	}
	return value
}

// command runs a program from dir with the run's environment, its output
// going where the subcommand's goes, and returns its exit code.
func (u *tapUpdate) command(dir string, quiet bool, name string, args ...string) int {
	cmd := exec.CommandContext(context.Background(), name, args...) //#nosec G204 -- git and ruby with the arguments the release gives
	cmd.Dir, cmd.Env, cmd.Stderr = dir, u.env, u.stderr
	if !quiet {
		cmd.Stdout = u.stdout
	}
	if err := cmd.Run(); err != nil {
		if exit, ok := errors.AsType[*exec.ExitError](err); ok {
			return exit.ExitCode()
		}
		fmt.Fprintf(u.stderr, "%s: %v\n", name, err)
		return 127
	}
	return 0
}

// checksumFor is every hash checksums.txt gives name, one per line, as the
// script's awk printed them.
func checksumFor(data, name string) string {
	var hashes []string
	for line := range strings.SplitSeq(data, "\n") {
		if fields := strings.Fields(line); len(fields) >= 2 && fields[1] == name {
			hashes = append(hashes, fields[0])
		}
	}
	return strings.Join(hashes, "\n")
}

// run renders, checks, commits and pushes the formula in the script's order.
func (u *tapUpdate) run() int {
	data, err := os.ReadFile(localPath(u.root, u.checksums)) //#nosec G304 -- the release's checksums.txt
	if err != nil {
		return u.errorf("%v", err)
	}
	values := map[string]string{}
	for _, entry := range [][2]string{
		{"SHA_DARWIN_ARM", "gitlab-mcp-server-darwin-arm64"},
		{"SHA_DARWIN_INTEL", "gitlab-mcp-server-darwin-amd64"},
		{"SHA_LINUX_ARM", "gitlab-mcp-server-linux-arm64"},
		{"SHA_LINUX_INTEL", "gitlab-mcp-server-linux-amd64"},
		{"SHA_NOTICES", noticesName},
	} {
		if values[entry[0]] = checksumFor(string(data), entry[1]); values[entry[0]] == "" {
			return u.errorf("no checksum for %s in %s", entry[1], u.checksums)
		}
	}
	licenseFile, err := filepath.Abs(localPath(u.root, "LICENSE"))
	if err != nil {
		return u.errorf("%v", err)
	}
	license, err := os.ReadFile(licenseFile) //#nosec G304 -- the repository's LICENSE
	if err != nil {
		return u.errorf("no LICENSE at %s to hash", licenseFile)
	}
	values["SHA_LICENSE"] = releaseassets.Digest(license)

	tap := localPath(u.root, u.tapDir)
	if info, statErr := os.Stat(filepath.Join(tap, ".git")); statErr != nil || !info.IsDir() {
		repo := u.lookup("TAP_REPO")
		if repo == "" {
			repo = defaultTapRepo
		}
		if code := u.command(u.root, false, "git", "clone", "--depth", "1", repo, u.tapDir); code != 0 {
			return code
		}
	}
	formula := filepath.Join(tap, filepath.FromSlash(tapFormula))
	if code := u.refuseADowngrade(formula); code != 0 {
		return code
	}
	if err = os.MkdirAll(filepath.Dir(formula), 0o755); err != nil { //#nosec G301 -- a directory of the tap's clone
		return u.errorf("%v", err)
	}
	if err = writeFileMode(formula, []byte(u.render(values)), 0o644); err != nil {
		return u.errorf("%v", err)
	}
	return u.commit(tap)
}

// refuseADowngrade refuses a formula that would move the tap back to an
// older release (issue 1323), by the order sort -V gives; the same version
// is a re-run and rewrites the formula.
func (u *tapUpdate) refuseADowngrade(formula string) int {
	held, err := os.ReadFile(formula) //#nosec G304 -- the formula in the tap's clone
	if err != nil {
		return 0
	}
	match := formulaVersion.FindSubmatch(held)
	if match == nil {
		return 0
	}
	current := string(match[1])
	if current != "" && current != u.version && sortVersionCompare(current, u.version) > 0 {
		return u.errorf("the tap already holds %s, newer than %s; a formula never moves back to an older release", current, u.version)
	}
	return 0
}

// render is the formula for this release.
func (u *tapUpdate) render(values map[string]string) string {
	base := releaseDownload + u.version
	pairs := []string{
		"${HEADER}", "# " + fileheader.CopyrightStatement + "\n# " + fileheader.LicenseStatement,
		"${DASH}", string(rune(0x2014)),
		"${VERSION}", u.version,
		"${BASE_URL}", base,
		"${LICENSE_URL}", licenseRaw + u.version + "/LICENSE",
	}
	for _, key := range []string{"SHA_DARWIN_ARM", "SHA_DARWIN_INTEL", "SHA_LINUX_ARM", "SHA_LINUX_INTEL", "SHA_LICENSE", "SHA_NOTICES"} {
		pairs = append(pairs, "${"+key+"}", values[key])
	}
	return strings.NewReplacer(pairs...).Replace(formulaTemplate)
}

// commit checks the formula with ruby -c, commits it to the clone, and
// pushes it, or with --dry-run shows the commit and pushes nothing.
func (u *tapUpdate) commit(tap string) int {
	steps := [][]string{
		{"ruby", "-c", tapFormula},
		{"git", "config", "user.name", tapAuthorName},
		{"git", "config", "user.email", tapAuthorEmail},
		{"git", "add", tapFormula},
	}
	for index, step := range steps {
		if code := u.command(tap, index == 0, step[0], step[1:]...); code != 0 {
			return code
		}
	}
	if u.command(tap, false, "git", "diff", "--cached", "--quiet") == 0 {
		fmt.Fprintf(u.stdout, "Tap formula already up to date for v%s\n", u.version)
		return 0
	}
	if code := u.command(tap, false, "git", "commit", "-m", "gitlab-mcp-server "+u.version); code != 0 {
		return code
	}
	if u.dryRun {
		fmt.Fprintln(u.stdout, "Dry run: the tap would receive this commit, nothing was pushed")
		if code := u.command(tap, false, "git", "--no-pager", "show", "--stat", "--format=%h %s", "HEAD"); code != 0 {
			return code
		}
		return u.command(tap, false, "git", "--no-pager", "diff", "HEAD~1", "--", tapFormula)
	}
	if code := u.command(tap, false, "git", "push", "origin", "HEAD:main"); code != 0 {
		return code
	}
	fmt.Fprintf(u.stdout, "Tap formula updated to v%s\n", u.version)
	return 0
}

// sortVersionCompare orders two versions as sort -V does: GNU's filevercmp,
// and the bytes when it finds them equal.
func sortVersionCompare(a, b string) int {
	if result := fileVersionCompare(a, b); result != 0 {
		return result
	}
	return strings.Compare(a, b)
}

// fileVersionCompare is gnulib's filevercmp for names that do not start
// with a dot: the names are compared without their file suffixes first, and
// whole when that finds them equal.
func fileVersionCompare(a, b string) int {
	switch {
	case a == b:
		return 0
	case a == "":
		return -1
	case b == "":
		return 1
	}
	aPrefix, bPrefix := filePrefixLen(a), filePrefixLen(b)
	result := versionRevCompare(a[:aPrefix], b[:bPrefix])
	if result != 0 || (aPrefix == len(a) && bPrefix == len(b)) {
		return result
	}
	return versionRevCompare(a, b)
}

// filePrefixLen is the length of s without the file suffix gnulib cuts:
// a run of `.` followed by a letter or `~` and then letters, digits or `~`,
// at the end.
func filePrefixLen(s string) int {
	prefix := 0
	for i := 0; i < len(s); {
		i++
		prefix = i
		for i+1 < len(s) && s[i] == '.' && (isASCIILetter(s[i+1]) || s[i+1] == '~') {
			for i += 2; i < len(s) && (isASCIILetter(s[i]) || isASCIIDigit(s[i]) || s[i] == '~'); i++ {
				continue
			}
		}
	}
	return prefix
}

func isASCIILetter(c byte) bool { return c|0x20 >= 'a' && c|0x20 <= 'z' }

func isASCIIDigit(c byte) bool { return c >= '0' && c <= '9' }

// versionOrder is the weight gnulib gives a byte outside a run of digits:
// the end first, then `~`, digits, letters, and everything else.
func versionOrder(s string, pos int) int {
	switch {
	case pos >= len(s):
		return -1
	case isASCIIDigit(s[pos]):
		return 0
	case isASCIILetter(s[pos]):
		return int(s[pos])
	case s[pos] == '~':
		return -2
	default:
		return int(s[pos]) + 256
	}
}

// versionRevCompare is gnulib's verrevcmp: runs of non-digits compared by
// versionOrder, runs of digits by their value.
func versionRevCompare(s1, s2 string) int {
	p1, p2 := 0, 0
	for p1 < len(s1) || p2 < len(s2) {
		if result := compareNonDigits(s1, s2, &p1, &p2); result != 0 {
			return result
		}
		if result := compareDigits(s1, s2, &p1, &p2); result != 0 {
			return result
		}
	}
	return 0
}

// compareNonDigits compares the runs of non-digits at p1 and p2 by
// versionOrder, advancing both past them.
func compareNonDigits(s1, s2 string, p1, p2 *int) int {
	for (*p1 < len(s1) && !isASCIIDigit(s1[*p1])) || (*p2 < len(s2) && !isASCIIDigit(s2[*p2])) {
		if c1, c2 := versionOrder(s1, *p1), versionOrder(s2, *p2); c1 != c2 {
			return c1 - c2
		}
		*p1++
		*p2++
	}
	return 0
}

// compareDigits compares the runs of digits at p1 and p2 by their value,
// leading zeros skipped, advancing both past them.
func compareDigits(s1, s2 string, p1, p2 *int) int {
	for *p1 < len(s1) && s1[*p1] == '0' {
		*p1++
	}
	for *p2 < len(s2) && s2[*p2] == '0' {
		*p2++
	}
	firstDiff := 0
	for *p1 < len(s1) && *p2 < len(s2) && isASCIIDigit(s1[*p1]) && isASCIIDigit(s2[*p2]) {
		if firstDiff == 0 {
			firstDiff = int(s1[*p1]) - int(s2[*p2])
		}
		*p1++
		*p2++
	}
	switch {
	case *p1 < len(s1) && isASCIIDigit(s1[*p1]):
		return 1
	case *p2 < len(s2) && isASCIIDigit(s2[*p2]):
		return -1
	}
	return firstDiff
}
