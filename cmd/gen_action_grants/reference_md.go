// referenceHead opens every language's page: the frontmatter the site reads
// the title and the description from, then the note that the page is
// generated. The site takes the title as the page's heading, so the page
// carries no heading of its own above its domains. The note is an MDX
// expression comment because MDX refuses an HTML comment, and it carries no
// space inside its delimiters because markdownlint reads "/* " as an emphasis
// marker followed by a space (MD037).
const referenceHead = "---\ntitle: %s\ndescription: \"%s\"\n---\n\n{/*Generated by cmd/gen_action_grants (make gen-action-grants); do not edit.*/}\n\n"

// referenceLanguage is the wording of one language's page: where it is
// written, its frontmatter and introduction, the table headings, and every
// phrase a row is made of. Action IDs, permission names, the GraphQL
// selections and the elements GitLab names stay as they are in every
// language, since a reader matches them against GitLab and this server rather
// than reads them as prose.
type referenceLanguage struct {
	// path is where the page is written, from the repository root.
	path string
	// title and description are the frontmatter; %s in description is the
	// GitLab release the table describes.
	title       string
	description string
	// intro is the introduction, one paragraph per entry; the one %s across
	// them is the GitLab release the table describes.
	intro []string
	// headers are the three columns of every domain's table.
	headers []string

	// notReachable opens the entry of an action no fine-grained token runs.
	notReachable string
	// oneOf opens the entry of an action with several ways of running.
	oneOf string
	// or separates ways, and the denials of the ways no token takes.
	or string
	// deniedWays leads into the ways no fine-grained token takes, after what
	// the others need.
	deniedWays string
	// notJudged is a request GitLab leaves out of the grant check.
	notJudged string
	// noPermission is a way that needs nothing.
	noPermission string
	// at joins a need's permissions to its boundaries, and boundaryOr joins
	// the boundaries.
	at         string
	boundaryOr string
	// boundaries are the words a boundary is written in where they are not
	// GitLab's own; a boundary it does not hold is written as GitLab names it.
	boundaries map[string]string
	// always and without close a part of the answer served empty: always, or
	// unless the grant holds what follows without.
	always  string
	without string

	// The denials, one format per cause; each %s is the element GitLab
	// names, and unresolvable's second %s is what GitLab does about it.
	mutationUndeclared string
	typeUndeclared     string
	payloadUndeclared  string
	unresolvable       string
	restTodo           string
	undeclared         string
	// The effects of a boundary that never resolves.
	effectRefused   string
	effectCommitted string
	effectNull      string
}

// referenceLanguages are the pages written, English first.
func referenceLanguages() []*referenceLanguage {
	return []*referenceLanguage{englishReference(), spanishReference()}
}

