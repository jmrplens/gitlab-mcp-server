// render writes the page, one table per domain.
func (l *referenceLanguage) render(table *finegrained.Table) []byte {
	version := table.DisplayVersion()
	var b strings.Builder
	fmt.Fprintf(&b, referenceHead, l.title, fmt.Sprintf(l.description, version))
	fmt.Fprintf(&b, strings.Join(l.intro, "\n\n"), version)
	b.WriteString("\n")
	byDomain := map[string][][]string{}
	var domains []string
	for i := range table.Actions {
		row := &table.Actions[i]
		domain, _, _ := strings.Cut(row.ID, ".")
		if _, seen := byDomain[domain]; !seen {
			domains = append(domains, domain)
		}
		description := table.Describe(row)
		byDomain[domain] = append(byDomain[domain], []string{"`" + row.ID + "`", l.needsText(description), l.servedEmptyText(description)})
	}
	slices.Sort(domains)
	for _, domain := range domains {
		fmt.Fprintf(&b, "\n## `%s`\n\n", domain)
		b.WriteString(docgen.RenderMarkdownTable(l.headers, nil, byDomain[domain]))
	}
	return []byte(b.String())
}

// needsText is what the action needs, way by way, and the ways no
// fine-grained token takes when some other way runs.
func (l *referenceLanguage) needsText(description *finegrained.Description) string {
	if description.Denied != nil {
		return l.notReachable + l.denialText(description.Denied)
	}
	ways := make([]string, len(description.AnyOf))
	for i, way := range description.AnyOf {
		ways[i] = l.wayText(way)
	}
	text := strings.Join(ways, l.or)
	if len(ways) > 1 {
		text = l.oneOf + text
	}
	if len(description.DeniedWays) == 0 {
		return text
	}
	reasons := make([]string, len(description.DeniedWays))
	for i := range description.DeniedWays {
		reasons[i] = l.denialText(&description.DeniedWays[i])
	}
	return text + l.deniedWays + strings.Join(reasons, l.or)
}

// wayText is what one way of running the action needs.
func (l *referenceLanguage) wayText(way finegrained.Way) string {
	parts := make([]string, 0, len(way.Needs)+1)
	for _, need := range way.Needs {
		parts = append(parts, l.needText(need))
	}
	if way.NotJudged {
		parts = append(parts, l.notJudged)
	}
	if len(parts) == 0 {
		return l.noPermission
	}
	return strings.Join(parts, "; ")
}

// needText is one need: every permission, at one of the boundaries.
func (l *referenceLanguage) needText(need finegrained.Need) string {
	boundaries := make([]string, len(need.At))
	for i, boundary := range need.At {
		boundaries[i] = l.boundary(boundary)
	}
	return strings.Join(need.Permissions, ", ") + l.at + strings.Join(boundaries, l.boundaryOr)
}

// boundary is one boundary in the page's words.
func (l *referenceLanguage) boundary(name string) string {
	if word, ok := l.boundaries[name]; ok {
		return word
	}
	return name
}

// servedEmptyText names the parts of the answer a fine-grained token may be
// served empty.
func (l *referenceLanguage) servedEmptyText(description *finegrained.Description) string {
	var parts []string
	for _, selection := range description.AlwaysEmpty {
		parts = append(parts, "`"+selection+"`"+l.always)
	}
	for _, position := range description.EmptyWithout {
		needs := make([]string, len(position.Needs))
		for i, need := range position.Needs {
			needs[i] = l.needText(need)
		}
		parts = append(parts, "`"+position.Selection+"`"+l.without+strings.Join(needs, "; ")+")")
	}
	return strings.Join(parts, ", ")
}

// denialText says why no fine-grained token reaches an action.
func (l *referenceLanguage) denialText(denial *finegrained.Denial) string {
	element := "`" + denial.Element + "`"
	switch denial.Cause {
	case finegrained.CauseMutationUndeclared:
		return fmt.Sprintf(l.mutationUndeclared, element)
	case finegrained.CauseTypeUndeclared:
		return fmt.Sprintf(l.typeUndeclared, element)
	case finegrained.CausePayloadUndeclared:
		return fmt.Sprintf(l.payloadUndeclared, element)
	case finegrained.CauseBoundaryUnresolvable:
		return fmt.Sprintf(l.unresolvable, element, l.unresolvedEffect(denial.Effect))
	case finegrained.CauseRESTTodo:
		return fmt.Sprintf(l.restTodo, element)
	default:
		return fmt.Sprintf(l.undeclared, element)
	}
}

// unresolvedEffect words what GitLab does where a boundary never resolves: a
// mutation's own check refuses it before anything runs, a write's answer is
// lost after the write commits, and a read answers null or leaves the object
// out of its list.
func (l *referenceLanguage) unresolvedEffect(effect finegrained.Effect) string {
	switch effect {
	case finegrained.EffectRefused:
		return l.effectRefused
	case finegrained.EffectCommittedThenNull:
		return l.effectCommitted
	default:
		return l.effectNull
	}
}
