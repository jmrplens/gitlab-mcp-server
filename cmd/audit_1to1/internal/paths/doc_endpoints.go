// DocEndpointsFile is where the documentation oracle is committed, relative to
// the repository root.
const DocEndpointsFile = "docs/development/gitlab-api-doc-endpoints.json"

// docEndpointsSchema is the shape of the oracle. A reader refuses another
// version rather than decode one whose fields may mean something else.
const docEndpointsSchema = 1

// docRepository is the project whose doc/api the oracle reads.
const docRepository = "gitlab-org/gitlab"

// docEndpointsNote is what the committed file says about itself.
const docEndpointsNote = "Every endpoint GitLab's API documentation spells as a `METHOD /path` line, read from doc/api of " +
	docRepository + " at the tag of the release the live API record was taken from, and the pages that spell each one. " +
	"cmd/audit_1to1 -scope=paths -check-endpoints holds every recorded REST endpoint to it. Generated by " +
	"make gen-api-doc-endpoints, which reads the pages over the network; do not edit by hand."

// DocEndpoints is the documentation oracle: what doc/api spelled out at one
// release, read once and committed so the endpoint comparison runs offline.
//
// It is committed rather than fetched by each run because a run used to need
// the network and two minutes of it, so nothing scheduled one: the cache it
// relied on held no page listing anywhere, and the declarations it judges went
// unjudged for as long as nobody ran it by hand (issue 1688). Reading the
// release the live record was taken from, rather than master, is what lets it
// gate: a page GitLab rewrites next week does not move it, and the re-pin that
// moves the live record regenerates it in the same change.
type DocEndpoints struct {
	SchemaVersion int                  `json:"schema_version"`
	Note          string               `json:"note"`
	Source        DocSource            `json:"source"`
	Endpoints     []DocumentedEndpoint `json:"endpoints"`
}

// DocSource is where the oracle was read from and how much of it there was.
type DocSource struct {
	Repository string `json:"repository"`
	// Ref is the tag of the repository the pages were read at.
	Ref string `json:"ref"`
	// Areas is how many pages were read.
	Areas int `json:"areas"`
	// SkippedAreas is how many were left unread on purpose: the generated
	// GraphQL reference, which holds no REST endpoint (see skippedAreaPrefix).
	SkippedAreas int `json:"skipped_areas"`
	// Endpoints is how many distinct method-and-path shapes the pages spell.
	Endpoints int `json:"endpoints"`
}

// DocumentedEndpoint is one endpoint the documentation spells out, with the
// path normalized the way the comparison reads it.
type DocumentedEndpoint struct {
	Method string `json:"method"`
	Path   string `json:"path"`
	// Areas are the pages that spell it, sorted, so a reader of a finding can
	// open the page an endpoint moved off.
	Areas []string `json:"areas"`
}

// methodPath is one endpoint line of a page, normalized.
type methodPath struct {
	Method string
	Path   string
}

// pageEndpoints reads the endpoints one documentation page spells out, each
// once, in the order the page spells them.
func pageEndpoints(page string) []methodPath {
	found := make([]methodPath, 0)
	for line := range strings.SplitSeq(page, "\n") {
		match := endpointLine.FindStringSubmatch(strings.TrimSpace(line))
		// A line has to carry a slash to be an endpoint. Without that, a
		// sentence beginning "GET is the method this endpoint takes" is read as
		// an endpoint called "is", and every recorded single-segment path then
		// matches something the documentation never said.
		if len(match) == 0 || !strings.Contains(match[2], "/") {
			continue
		}
		segments := normalizePath(match[2])
		if len(segments) == 0 {
			continue
		}
		endpoint := methodPath{Method: match[1], Path: "/" + strings.Join(segments, "/")}
		if !slices.Contains(found, endpoint) {
			found = append(found, endpoint)
		}
	}
	return found
}

// BuildDocEndpoints reads doc/api through fetcher, which reads it at ref, and
// returns the oracle as the file commits it.
//
// Every page has to be read. A page that will not fetch used to be counted and
// skipped, which was the right answer for a comparison run on the spot and is
// the wrong one for a committed oracle: every endpoint documented only there
// would stand undocumented in the repository until the next regeneration, as
// a finding about the fetch.
func BuildDocEndpoints(ctx context.Context, fetcher *apidocs.Fetcher, ref string) ([]byte, error) {
	areas, err := fetcher.Areas(ctx)
	if err != nil {
		return nil, fmt.Errorf("list doc/api at %s: %w", ref, err)
	}
	oracle := DocEndpoints{
		SchemaVersion: docEndpointsSchema,
		Note:          docEndpointsNote,
		Source:        DocSource{Repository: docRepository, Ref: ref},
	}
	byKey := map[methodPath]*DocumentedEndpoint{}
	for _, area := range areas {
		if strings.HasPrefix(area, skippedAreaPrefix) {
			oracle.Source.SkippedAreas++
			continue
		}
		page, fetchErr := fetcher.Fetch(ctx, area)
		if fetchErr != nil {
			return nil, fmt.Errorf("read doc/api/%s.md at %s: %w", area, ref, fetchErr)
		}
		oracle.Source.Areas++
		for _, endpoint := range pageEndpoints(page) {
			documented := byKey[endpoint]
			if documented == nil {
				documented = &DocumentedEndpoint{Method: endpoint.Method, Path: endpoint.Path}
				byKey[endpoint] = documented
			}
			// The listing is sorted and each area is read once, so the
			// pages arrive here in order and none of them twice.
			documented.Areas = append(documented.Areas, area)
		}
	}
	if len(byKey) == 0 {
		return nil, fmt.Errorf("no page of doc/api at %s spells an endpoint line, so the pages no longer write them the way this reads them", ref)
	}
	oracle.Endpoints = make([]DocumentedEndpoint, 0, len(byKey))
	for _, documented := range byKey {
		oracle.Endpoints = append(oracle.Endpoints, *documented)
	}
	slices.SortFunc(oracle.Endpoints, func(a, b DocumentedEndpoint) int {
		return cmp.Or(strings.Compare(a.Path, b.Path), strings.Compare(a.Method, b.Method))
	})
	oracle.Source.Endpoints = len(oracle.Endpoints)
	// Marshaling a struct of strings, ints and slices cannot fail, and this
	// repository's rule for that is to say so at the leaf.
	return append(cmdutil.Must(json.MarshalIndent(oracle, "", "  ")), '\n'), nil
}

// readDocEndpoints reads the committed oracle under root.
func readDocEndpoints(root string) (DocEndpoints, error) {
	raw, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(DocEndpointsFile)))
	if err != nil {
		return DocEndpoints{}, fmt.Errorf("read the documentation oracle (make gen-api-doc-endpoints writes it): %w", err)
	}
	var oracle DocEndpoints
	if decodeErr := json.Unmarshal(raw, &oracle); decodeErr != nil {
		return DocEndpoints{}, fmt.Errorf("decode %s: %w", DocEndpointsFile, decodeErr)
	}
	if oracle.SchemaVersion != docEndpointsSchema {
		return DocEndpoints{}, fmt.Errorf("%s is schema version %d and this build reads version %d: regenerate it with make gen-api-doc-endpoints",
			DocEndpointsFile, oracle.SchemaVersion, docEndpointsSchema)
	}
	return oracle, nil
}

// documented returns the oracle's endpoints by method, as the segments the
// comparison matches against.
func (o DocEndpoints) documented() map[string][][]string {
	byMethod := map[string][][]string{}
	for _, endpoint := range o.Endpoints {
		byMethod[endpoint.Method] = append(byMethod[endpoint.Method], normalizePath(endpoint.Path))
	}
	return byMethod
}

// ReleaseRef returns the tag of gitlab-org/gitlab that the live API record's
// release was built from: v19.5.0-ee for a record of 19.5.0-ee. It is the ref
// the documentation oracle is read at, so the two oracles R-PATH holds a
// request to speak for one GitLab.
func ReleaseRef(root string) (string, error) {
	record, err := apilive.Read(recordDir(root))
	if err != nil {
		return "", err
	}
	if record.Source.Version == "" {
		return "", errors.New("the live API record names no release, so there is no tag to read the documentation at")
	}
	return "v" + record.Source.Version, nil
}
